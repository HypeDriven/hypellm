#!/usr/bin/env python3
"""Maintain the offline wiki index and check local links; standard library only."""

import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit

WIKI = Path(__file__).resolve().parent
REPOSITORY = WIKI.parent
INDEX = WIKI / 'assets/search-index.js'


class Page(HTMLParser):
    def __init__(self, path):
        super().__init__(convert_charrefs=True)
        self.path = path
        self.ids = set()
        self.errors = []
        self.links = []
        self.page_title = ''
        self.group = ''
        self.article = False
        self.heading = None
        self.heading_id = ''
        self.heading_text = []
        self.current = None
        self.entries = []
        self.feed(path.read_text(encoding='utf-8'))
        self.finish_entry()

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        anchor = attributes.get('id')
        if anchor:
            if anchor in self.ids:
                self.errors.append(f'duplicate id: {anchor}')
            self.ids.add(anchor)
        if tag == 'body':
            self.page_title = attributes.get('data-page-title', '')
            self.group = attributes.get('data-page-group', '')
        for key in ('href', 'src'):
            if attributes.get(key):
                self.links.append(attributes[key])
        if tag == 'article':
            self.article = True
        if self.article:
            if tag in ('h1', 'h2', 'h3', 'h4', 'h5', 'h6'):
                self.finish_entry()
                self.heading = tag
                self.heading_id = anchor or ''
                self.heading_text = []
            elif self.current and tag in ('p', 'li', 'tr', 'td', 'th', 'pre', 'br'):
                self.current['text'] += ' '

    def handle_endtag(self, tag):
        if tag == self.heading:
            title = ''.join(self.heading_text).strip()
            url = self.path.relative_to(WIKI).as_posix()
            if self.heading_id:
                url += '#' + self.heading_id
            self.current = {
                'page': self.page_title, 'group': self.group,
                'heading': title, 'url': url, 'text': '',
            }
            self.heading = None
        if tag == 'article':
            self.finish_entry()
            self.article = False
        elif self.article and self.current and tag in ('p', 'li', 'tr', 'td', 'th', 'pre'):
            self.current['text'] += ' '

    def handle_data(self, data):
        if not self.article:
            return
        if self.heading:
            self.heading_text.append(data)
        elif self.current:
            self.current['text'] += data

    def finish_entry(self):
        if self.current:
            self.current['text'] = re.sub(r'\s+', ' ', self.current['text']).strip()
            self.entries.append(self.current)
            self.current = None


def read_pages():
    return {path: Page(path) for path in sorted(WIKI.rglob('*.html'))}


def index_text(pages):
    entries = [entry for page in pages.values() for entry in page.entries]
    return '// Generated by python3 spec/wiki.py update; edit the HTML pages.\n' + \
        'window.HYPELLM_WIKI_INDEX = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ';\n'


def check(pages):
    errors = []
    for path, page in pages.items():
        for error in page.errors:
            errors.append(f'{path.relative_to(REPOSITORY)}: {error}')
        if not page.entries or not page.page_title or not page.group:
            errors.append(f'{path.relative_to(REPOSITORY)}: missing article or page metadata')
        for link in page.links:
            url = urlsplit(link)
            if url.scheme or url.netloc:
                continue
            target = (path.parent / unquote(url.path)).resolve() if url.path else path
            if not target.is_relative_to(REPOSITORY):
                errors.append(f'{path.relative_to(REPOSITORY)}: link escapes repository: {link}')
            elif not target.exists():
                errors.append(f'{path.relative_to(REPOSITORY)}: missing link target: {link}')
            elif url.fragment and target in pages and unquote(url.fragment) not in pages[target].ids:
                errors.append(f'{path.relative_to(REPOSITORY)}: missing section anchor: {link}')
    if not INDEX.exists() or INDEX.read_text(encoding='utf-8') != index_text(pages):
        errors.append('Search index is stale; run python3 spec/wiki.py update')
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    sections = sum(len(page.entries) for page in pages.values())
    print(f'Wiki checks passed: {len(pages)} pages, {sections} sections; local links, anchors and search index are valid.')
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('update', 'check'))
    args = parser.parse_args()
    pages = read_pages()
    if args.command == 'update':
        INDEX.write_text(index_text(pages), encoding='utf-8')
        print(f'Updated the search index for {len(pages)} pages.')
    return check(pages)


if __name__ == '__main__':
    sys.exit(main())
